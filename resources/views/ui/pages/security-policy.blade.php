                        <h2>Security Policy</h2>
                        <p><strong>Last Updated:</strong> August 2026</p>
                        <p>StorageKeys ("StorageKeys", "we", "our", or "us") is committed to maintaining a safe and secure environment for customers and their stored belongings. As a provider of self storage, business storage, warehouse storage, climate-controlled storage, luggage storage, and vehicle storage solutions across the UAE, we understand the importance of protecting customer property while providing convenient access to our facilities.</p>
                        <p>This Security Policy explains the security measures maintained by StorageKeys, the responsibilities of customers, and the procedures we follow to help protect our facilities and stored belongings.</p>
                    </section>

                    <section id="purpose">
                        <h2>1. Purpose of This Policy</h2>
                        <p>This Security Policy outlines StorageKeys' approach to physical security, access control, surveillance, fire safety, and security incident management. It applies to customers using StorageKeys facilities and services, including personal storage, business storage, warehouse storage, climate-controlled storage, luggage storage, and vehicle storage.</p>
                        <p>The policy is intended to provide transparency regarding our general security practices. Specific security arrangements, insurance coverage, and customer obligations may also be governed by the individual storage agreement.</p>
                    </section>

                    <section id="our-security-measures">
                        <h2>2. Our Security Measures</h2>
                        <p>StorageKeys uses multiple security measures to help maintain a secure storage environment. These measures are designed to deter unauthorised access, identify potential security concerns, and protect customers and their belongings.</p>
                        <p>Our security measures include:</p>
                        <ul>
                            <li>CCTV surveillance across relevant areas of our facilities.</li>
                            <li>Controlled access to storage areas.</li>
                            <li>Security monitoring and facility oversight.</li>
                            <li>Appropriate fire detection and safety measures.</li>
                            <li>Secure storage areas designed to limit unauthorised access.</li>
                            <li>Procedures for responding to security and safety incidents.</li>
                            <li>Regular attention to the condition and security of our facilities.</li>
                        </ul>
                        <p>Security measures may vary depending on the type and location of the storage facility. We may also introduce additional security technologies or procedures as our operations develop.</p>
                    </section>

                    <section id="cctv-and-monitoring">
                        <h2>3. CCTV and Monitoring</h2>
                        <p>StorageKeys uses CCTV and other monitoring measures to support the security and safety of our facilities.</p>
                        <p>Cameras may cover areas such as entrances, access points, common areas, loading and unloading areas, and other relevant locations. CCTV is used to help deter unauthorised activity, monitor facility security, and assist with investigations when an incident occurs.</p>
                        <p>Access to security footage is restricted to authorised personnel and may be provided to law enforcement or other relevant authorities where required by law. CCTV systems are an important part of our security approach, but they cannot guarantee that every incident will be prevented or detected.</p>
                    </section>

                    <section id="24-7-customer-access">
                        <h2>4. 24/7 Customer Access</h2>
                        <p>StorageKeys provides customers with 24/7 access to their storage facilities, subject to the terms of their individual storage agreement and applicable facility procedures. Customers are responsible for keeping their access credentials, keys, or other access methods secure. Access information must not be shared with unauthorised individuals.</p>
                        <p>Customers who allow employees, family members, representatives, movers, or other third parties to access their storage space are responsible for ensuring that those individuals are authorised and follow StorageKeys' applicable rules.</p>
                        <p>StorageKeys may temporarily restrict access when reasonably necessary for security, emergency situations, maintenance, legal requirements, or other circumstances affecting the safe operation of the facility.</p>
                    </section>

                    <section id="fire-and-safety-protection">
                        <h2>5. Fire and Safety Protection</h2>
                        <p>Fire prevention and general safety are important parts of StorageKeys' facility security practices. We maintain appropriate fire safety measures and take reasonable steps to keep storage areas, access routes, and common areas suitable for safe use.</p>
                        <p>Customers must not store materials that could create a significant fire, explosion, chemical, or health risk. Emergency exits, access routes, fire equipment, and other designated safety areas must remain clear at all times. Customers must follow facility safety instructions and any directions issued by StorageKeys personnel or emergency authorities during an emergency.</p>
                    </section>

                    <section id="prohibited-items">
                        <h2>6. Prohibited and Restricted Items</h2>
                        <p>To protect customers, employees, facilities, and stored belongings, certain items are prohibited from StorageKeys facilities.</p>
                        <p>Customers must not store:</p>
                        <ul>
                            <li>Illegal goods, stolen property, or items prohibited under UAE law.</li>
                            <li>Weapons, ammunition, explosives, or other dangerous weapons.</li>
                            <li>Flammable liquids, fuels, fireworks, or explosive materials.</li>
                            <li>Toxic, corrosive, radioactive, or hazardous chemicals.</li>
                            <li>Illegal drugs or controlled substances.</li>
                            <li>Live animals or materials requiring ongoing care.</li>
                            <li>Perishable food or items likely to spoil, decay, or attract pests.</li>
                            <li>Hazardous waste or materials requiring specialist handling.</li>
                            <li>Items that produce excessive odours, fumes, leakage, or contamination.</li>
                            <li>Any other item that creates an unreasonable health, safety, environmental, or security risk.</li>
                        </ul>
                        <p>StorageKeys may require customers to remove prohibited items and may take appropriate action where stored property presents a safety or security concern.</p>
                    </section>

                    <section id="insurance-coverage">
                        <h2>7. Insurance Coverage</h2>
                        <p>StorageKeys provides automatic and comprehensive insurance coverage for stored belongings, subject to the applicable insurance terms and conditions.</p>
                        <p>Coverage may be subject to specific limits, exclusions, requirements, and other conditions. Customers should review the insurance provisions applicable to their storage agreement to understand the scope of protection provided. Insurance coverage does not remove the customer's responsibility to store belongings appropriately or comply with StorageKeys' storage and safety requirements.</p>
                    </section>

                    <section id="customer-security-responsibilities">
                        <h2>8. Customer Security Responsibilities</h2>
                        <p>Security is a shared responsibility. Customers are expected to take reasonable precautions when using StorageKeys facilities.</p>
                        <p>Customers should:</p>
                        <ul>
                            <li>Keep keys, access credentials, and security information secure.</li>
                            <li>Never share access credentials with unauthorised persons.</li>
                            <li>Secure their storage space properly when leaving the facility.</li>
                            <li>Ensure authorised guests or representatives follow facility rules.</li>
                            <li>Report lost keys or compromised access credentials promptly.</li>
                            <li>Report suspicious activity or security concerns to StorageKeys.</li>
                            <li>Avoid storing prohibited, dangerous, or hazardous materials.</li>
                            <li>Keep emergency routes and facility areas clear.</li>
                            <li>Maintain accurate contact information with StorageKeys.</li>
                        </ul>
                        <p>Customers should promptly notify StorageKeys if they notice signs of unauthorised access, attempted theft, damage, or other unusual activity.</p>
                    </section>

                    <section id="incident-management">
                        <h2>9. Security Incident Management</h2>
                        <p>If StorageKeys becomes aware of a suspected theft, unauthorised access, security breach, or other significant incident, we will take reasonable steps to assess and respond to the situation. Depending on the nature of the incident, this may include reviewing available CCTV footage, checking access information, securing affected areas, investigating the circumstances, and cooperating with relevant authorities.</p>
                        <p>Customers who become aware of a security concern should contact StorageKeys as soon as reasonably possible. Prompt reporting allows us to assess the situation and take appropriate action.</p>
                        <p>Where an incident involves suspected criminal activity, StorageKeys may cooperate with UAE law enforcement or other relevant authorities and provide information where legally required.</p>
                    </section>

                    <section id="limitations-of-security">
                        <h2>10. Limitations of Security</h2>
                        <p>StorageKeys takes reasonable measures to maintain secure facilities, but no physical security system can guarantee complete protection against every possible risk.</p>
                        <p>CCTV, access controls, monitoring systems, fire safety measures, and other safeguards can reduce risks but cannot eliminate the possibility of theft, accidental damage, unauthorised access, system failures, natural events, or other unforeseen circumstances.</p>
                        <p>Customers should therefore follow all facility rules and take reasonable care of their stored belongings. Insurance protection remains subject to the applicable insurance terms, conditions, exclusions, and coverage limits.</p>
                    </section>

                    <section id="policy-updates">
                        <h2>11. Policy Updates</h2>
                        <p>StorageKeys may update this Security Policy from time to time to reflect changes in our facilities, security practices, technology, legal requirements, or business operations.</p>
                        <p>Any updates will be published on this page with a revised "Last Updated" date. Customers are encouraged to review this policy periodically to remain informed about our security practices.</p>
